# === Validation ===
validate_map () {
    local sel=$1
    if ! [[ $sel =~ ^[0-9]+$ ]] || ((sel < 1 || sel > total_maps)); then
        echo "Error: Invalid map selection '$sel'. Valid range: 1-$total_maps" >&2
        return 1
    fi
    return 0
}

validate_map_data () {
    local sel=$1
    local expected=$((mapw * maph))
    local actual=${#map[@]}

    if ((actual != expected)); then
        echo "Error: Map $sel has $actual cells but expected $expected (${mapw}x${maph})" >&2
        return 1
    fi

    # validate exit coordinates are within bounds
    local er=${exit_row[$sel]:-0} ec=${exit_col[$sel]:-0}
    if ((er < 0 || er >= maph || ec < 0 || ec >= mapw)); then
        echo "Error: Map $sel exit position ($er,$ec) is out of bounds (${mapw}x${maph})" >&2
        return 1
    fi

    # validate exit is on an empty cell
    if ((map[er * mapw + ec] != 0)); then
        echo "Error: Map $sel exit position ($er,$ec) is not on an empty cell" >&2
        return 1
    fi

    # validate all cell values are in range
    local i
    for ((i = 0; i < actual; i++)); do
        if ((map[i] < 0 || map[i] > 9)); then
            echo "Error: Map $sel has invalid cell value '${map[i]}' at index $i (must be 0-9)" >&2
            return 1
        fi
    done

    return 0
}

